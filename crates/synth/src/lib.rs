//! Synthesis with Yosys.
//!
//! The script is generated from the family database: read the sources, fix
//! the top with `hierarchy`, run the family's `synth_*` command (or the
//! user's own script), record `stat -json`, and write the netlist format the
//! chosen P&R backend consumes (JSON for nextpnr, EBLIF for VPR, EDIF for
//! ISE/Vivado, VQM for Quartus).

pub mod report;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use fpgaflow_core::family::{self, Backend, Family, Flatten, NetlistFormat};
use fpgaflow_core::job::JobSpec;
use fpgaflow_core::project::{Frontend, Project, ProjectError};
use fpgaflow_core::stage::Plan;
use fpgaflow_core::{tools, UserConfig};

#[derive(Debug, thiserror::Error)]
pub enum SynthError {
    #[error(transparent)]
    Project(#[from] ProjectError),
    #[error("no target family: set [target] family in fpgaflow.toml (see `fpgaflow families`)")]
    NoFamily,
    #[error("unknown family {0:?} (see `fpgaflow families`)")]
    UnknownFamily(String),
    #[error("unknown backend {0:?}")]
    UnknownBackend(String),
    #[error("backend {backend:?} does not support family {family:?} (it supports: {})", supported.join(", "))]
    BackendNotForFamily {
        family: String,
        backend: String,
        supported: Vec<String>,
    },
    #[error("no RTL files found (check [sources] rtl in fpgaflow.toml)")]
    NoRtl,
    #[error("yosys is not installed (run `fpgaflow doctor`)")]
    NoYosys,
}

/// Which family and backend a project targets, after applying overrides.
#[derive(Debug, Clone, Copy)]
pub struct Target {
    pub family: &'static Family,
    pub backend: &'static Backend,
}

/// Resolve the project's `[target]`, with optional command-line overrides.
pub fn resolve_target(
    project: &Project,
    family_override: Option<&str>,
    backend_override: Option<&str>,
) -> Result<Target, SynthError> {
    let t = project.file.target.as_ref();
    let fam_id = family_override
        .map(str::to_string)
        .or_else(|| t.and_then(|t| t.family.clone()))
        .ok_or(SynthError::NoFamily)?;
    let family =
        family::family(&fam_id).ok_or_else(|| SynthError::UnknownFamily(fam_id.clone()))?;
    // The project's backend only applies to the project's family: overriding
    // the family without naming a backend picks that family's default.
    let project_backend = if family_override.is_some() {
        None
    } else {
        t.and_then(|t| t.backend.clone())
    };
    let be_id = backend_override
        .map(str::to_string)
        .or(project_backend)
        .unwrap_or_else(|| family.default_backend().to_string());
    let backend =
        family::backend(&be_id).ok_or_else(|| SynthError::UnknownBackend(be_id.clone()))?;
    if !family.backends.contains(&be_id) {
        return Err(SynthError::BackendNotForFamily {
            family: fam_id,
            backend: be_id,
            supported: family.backends.clone(),
        });
    }
    Ok(Target { family, backend })
}

/// Everything the script generator needs; separate from [`Project`] so it
/// can be tested directly.
#[derive(Debug, Clone)]
pub struct ScriptRequest<'a> {
    pub files: Vec<PathBuf>,
    pub include_dirs: Vec<PathBuf>,
    pub defines: BTreeMap<String, String>,
    pub top: Option<String>,
    pub frontend: Frontend,
    pub family: &'a Family,
    /// User script replacing the family's synth command.
    pub custom_script: Option<PathBuf>,
    pub extra: Vec<String>,
    pub keep_hierarchy: bool,
    pub netlist_format: NetlistFormat,
    pub netlist: PathBuf,
    pub stat: PathBuf,
}

fn q(p: &Path) -> String {
    format!("\"{}\"", p.display())
}

/// The Yosys command that writes `fmt` to `path`. The flags match what the
/// `synth_*` commands themselves use for these formats.
pub fn writer(fmt: NetlistFormat, path: &Path) -> String {
    let p = q(path);
    match fmt {
        NetlistFormat::Json => format!("write_json {p}"),
        NetlistFormat::Edif => format!("write_edif -pvector bra {p}"),
        NetlistFormat::Blif => format!("write_blif {p}"),
        NetlistFormat::Eblif => format!("write_blif -attr -param -cname -conn {p}"),
        NetlistFormat::Vqm => {
            format!("write_verilog -attr2comment -defparam -nohex -decimal -renameprefix syn_ {p}")
        }
    }
}

/// Generate the synthesis script.
pub fn script(r: &ScriptRequest<'_>) -> String {
    let mut s = String::from(
        "# Generated by fpgaflow; edits are overwritten. Use [synth] script/extra instead.\n",
    );

    let mut read = match r.frontend {
        Frontend::Verilog => String::from("read_verilog -sv"),
        Frontend::Slang => {
            s.push_str("plugin -i slang\n");
            String::from("read_slang")
        }
    };
    for d in &r.include_dirs {
        read.push_str(&format!(" -I {}", q(d)));
    }
    for (k, v) in &r.defines {
        read.push_str(&format!(" -D{k}={v}"));
    }
    if let (Frontend::Slang, Some(t)) = (r.frontend, &r.top) {
        read.push_str(&format!(" --top {t}"));
    }
    for f in &r.files {
        read.push(' ');
        read.push_str(&q(f));
    }
    s.push_str(&read);
    s.push('\n');

    match &r.top {
        Some(t) => s.push_str(&format!("hierarchy -check -top {t}\n")),
        None => s.push_str("hierarchy -check -auto-top\n"),
    }

    match &r.custom_script {
        Some(path) => s.push_str(&format!("script {}\n", q(path))),
        None => {
            // Flags attach to the first command of the family's sequence.
            let mut cmds = r
                .family
                .yosys
                .split(';')
                .map(str::trim)
                .filter(|c| !c.is_empty());
            if let Some(first) = cmds.next() {
                let mut c = first.to_string();
                if r.family.top_flag {
                    if let Some(t) = &r.top {
                        c.push_str(&format!(" -top {t}"));
                    }
                }
                match (r.family.flatten, r.keep_hierarchy) {
                    (Flatten::Flag, false) => c.push_str(" -flatten"),
                    (Flatten::Default, true) => c.push_str(" -noflatten"),
                    _ => {}
                }
                s.push_str(&c);
                s.push('\n');
            }
            for c in cmds {
                s.push_str(c);
                s.push('\n');
            }
        }
    }
    for c in &r.extra {
        s.push_str(c);
        s.push('\n');
    }
    // Name the anonymous $abc$/$auto$ cells after the signals they drive, so
    // timing reports, the device view and AREA_GROUP patterns (`u_x.*`) can
    // tell which module a cell came from.
    s.push_str("autoname\n");
    // flatten leaves $scopeinfo cells recording the old hierarchy; they are
    // not hardware, and write_edif emits them as references to an undefined
    // cell, which ISE's ngdbuild rejects (NgdBuild:175).
    s.push_str("delete t:$scopeinfo\n");
    s.push_str(&format!("tee -q -o {} stat -json\n", q(&r.stat)));
    s.push_str(&writer(r.netlist_format, &r.netlist));
    s.push('\n');
    s
}

/// A planned synthesis run plus what it will produce.
#[derive(Debug, Clone)]
pub struct SynthPlan {
    pub plan: Plan,
    pub target: Target,
    pub netlist: PathBuf,
    pub stat: PathBuf,
    pub log: PathBuf,
}

pub fn plan_synth(
    project: &Project,
    cfg: &UserConfig,
    target: Target,
) -> Result<SynthPlan, SynthError> {
    let yosys = tools::resolve("yosys", cfg).ok_or(SynthError::NoYosys)?;
    let files = project.rtl_files()?;
    if files.is_empty() {
        return Err(SynthError::NoRtl);
    }
    let workdir = project.stage_dir("synth");
    let top = project.file.project.top.clone();
    let stem = top
        .clone()
        .unwrap_or_else(|| project.file.project.name.clone());
    let netlist = workdir.join(format!("{stem}.{}", target.backend.netlist.extension()));
    let stat = workdir.join("stat.json");
    let log = workdir.join("synth.log");
    let script_path = workdir.join("synth.ys");
    let synth = &project.file.synth;

    let text = script(&ScriptRequest {
        files,
        include_dirs: project.include_dirs(),
        defines: project.file.sources.defines.clone(),
        top,
        frontend: synth.frontend,
        family: target.family,
        custom_script: synth.script.as_ref().map(|p| project.root.join(p)),
        extra: synth.extra.clone(),
        keep_hierarchy: synth.keep_hierarchy,
        netlist_format: target.backend.netlist,
        netlist: netlist.clone(),
        stat: stat.clone(),
    });

    // -q keeps the terminal to warnings and errors; -l still logs everything.
    let job =
        JobSpec::new("synth", yosys, &workdir).args(["-q", "-l", "synth.log", "-s", "synth.ys"]);
    let plan = Plan {
        stage: "synth".into(),
        workdir,
        jobs: vec![job],
        outputs: vec![netlist.clone(), stat.clone()],
        verdict_job: None,
        files: vec![(script_path, text)],
    };
    Ok(SynthPlan {
        plan,
        target,
        netlist,
        stat,
        log,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use fpgaflow_core::project::{ProjectFile, TargetSection};

    fn req<'a>(family: &'a Family, fmt: NetlistFormat) -> ScriptRequest<'a> {
        ScriptRequest {
            files: vec!["/p/rtl/a.sv".into()],
            include_dirs: vec![],
            defines: BTreeMap::new(),
            top: Some("top".into()),
            frontend: Frontend::Verilog,
            family,
            custom_script: None,
            extra: vec![],
            keep_hierarchy: false,
            netlist_format: fmt,
            netlist: "/p/build/synth/top.out".into(),
            stat: "/p/build/synth/stat.json".into(),
        }
    }

    fn body(s: &str) -> Vec<&str> {
        s.lines().skip(1).collect()
    }

    #[test]
    fn spartan3a_script_for_ise() {
        let f = family::family("spartan3a").unwrap();
        let s = script(&req(f, NetlistFormat::Edif));
        assert_eq!(
            body(&s),
            [
                r#"read_verilog -sv "/p/rtl/a.sv""#,
                "hierarchy -check -top top",
                "synth_xilinx -family xc3sa -ise -top top -flatten",
                "autoname",
                "delete t:$scopeinfo",
                r#"tee -q -o "/p/build/synth/stat.json" stat -json"#,
                r#"write_edif -pvector bra "/p/build/synth/top.out""#,
            ]
        );
    }

    #[test]
    fn ecp5_gets_no_top_or_flatten_flag() {
        let f = family::family("ecp5").unwrap();
        let s = script(&req(f, NetlistFormat::Json));
        assert!(s.contains("\nsynth_ecp5\n"), "{s}");
        assert!(s.contains("hierarchy -check -top top"));
    }

    #[test]
    fn generic_flags_go_on_first_command_only() {
        let f = family::family("generic").unwrap();
        let s = script(&req(f, NetlistFormat::Eblif));
        assert!(
            s.contains("\nsynth -top top -flatten\nabc -lut 6\nopt_clean\n"),
            "{s}"
        );
        assert!(s.contains("write_blif -attr -param -cname -conn"));
    }

    #[test]
    fn hierarchy_options_follow_the_family() {
        let mut r = req(family::family("ice40").unwrap(), NetlistFormat::Json);
        assert!(
            script(&r).contains("\nsynth_ice40 -top top\n"),
            "flattens by default"
        );
        r.keep_hierarchy = true;
        assert!(script(&r).contains("\nsynth_ice40 -top top -noflatten\n"));
        let mut r = req(family::family("xc7").unwrap(), NetlistFormat::Eblif);
        r.keep_hierarchy = true;
        assert!(script(&r).contains("\nsynth_xilinx -family xc7 -top top\n"));
    }

    #[test]
    fn custom_script_extra_and_slang() {
        let f = family::family("ice40").unwrap();
        let mut r = req(f, NetlistFormat::Json);
        r.custom_script = Some("/p/synth/my.ys".into());
        r.extra = vec!["opt -full".into()];
        r.frontend = Frontend::Slang;
        r.defines.insert("W".into(), "8".into());
        let s = script(&r);
        assert!(
            s.contains("plugin -i slang\nread_slang -DW=8 --top top \"/p/rtl/a.sv\"\n"),
            "{s}"
        );
        assert!(s.contains("script \"/p/synth/my.ys\"\nopt -full\n"), "{s}");
        assert!(!s.contains("synth_ice40"));
    }

    #[test]
    fn target_resolution() {
        let dir = tempfile::tempdir().unwrap();
        let mut f = ProjectFile::new("t");
        f.target = Some(TargetSection {
            family: Some("spartan3a".into()),
            ..Default::default()
        });
        let p = Project::create(dir.path(), f).unwrap();
        let t = resolve_target(&p, None, None).unwrap();
        assert_eq!(t.backend.id, "ise");
        assert!(matches!(
            resolve_target(&p, None, Some("nextpnr")),
            Err(SynthError::BackendNotForFamily { .. })
        ));
        assert_eq!(
            resolve_target(&p, Some("ice40"), None).unwrap().backend.id,
            "nextpnr"
        );
        // The project's backend (ise) must not leak into an overridden family.
        let mut p2 = p.clone();
        p2.file.target.as_mut().unwrap().backend = Some("ise".into());
        assert_eq!(
            resolve_target(&p2, Some("xc7"), None).unwrap().backend.id,
            "vpr"
        );
        assert!(matches!(
            resolve_target(&p, Some("nope"), None),
            Err(SynthError::UnknownFamily(_))
        ));
    }
}
