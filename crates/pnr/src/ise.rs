#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Resource {
    pub name: String,
    pub used: u64,
    pub available: u64,
}

static MRP_ROW: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^  Number of (.+?):\s+([\d,]+) out of\s+([\d,]+)").unwrap());

fn n(s: &str) -> u64 {
    s.replace(',', "").parse().unwrap_or(0)
}

/// One step of a timing path: a delay at a site pin.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct PathStep {
    /// Site, e.g. `SLICE_X13Y62`, or a pad's ball, e.g. `P10`.
    pub site: String,
    /// Site pin, e.g. `YQ`, `G2`, `COUT`.
    pub pin: String,
    /// `Tcko`, `Tilo`, ... for logic; `net` for routing.
    pub kind: String,
    pub delay_ns: f64,
    /// Logical resources (signal and cell names) at this step.
    pub logical: Vec<String>,
}

impl PathStep {
    pub fn is_net(&self) -> bool {
        self.kind == "net"
    }
}

/// A detailed path from a `trce -v` report.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct TimingPath {
    pub slack_ns: f64,
    pub source: String,
    pub dest: String,
    pub delay_ns: Option<f64>,
    pub levels: Option<u32>,
    pub steps: Vec<PathStep>,
}

static TWR_SLACK: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^Slack:\s+(-?[\d.]+)ns").unwrap());
static TWR_ENDPOINT: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"^\s+(Source|Destination):\s+(.+?)(?:\s+\([A-Z]+\))?\s*$").unwrap()
});
static TWR_DELAY: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"^\s+Data Path Delay:\s+([\d.]+)ns\s+\(Levels of Logic = (\d+)\)").unwrap()
});
static TWR_STEP: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"^\s{4}(\S+)\.(\S+)\s+(net \(fanout=\d+\)|T\w+)\s+(-?[\d.]+)\s*(\S.*)?$").unwrap()
});
static TWR_MORE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^\s{40,}(\S.*)$").unwrap());

/// The detailed data paths of a timing report, worst slack first. Paths
/// without steps (pulse-width checks) and duplicates are dropped.
pub fn parse_timing_paths(text: &str) -> Vec<TimingPath> {
    let mut paths: Vec<TimingPath> = Vec::new();
    let mut cur: Option<TimingPath> = None;
    let mut in_steps = false;
    let flush = |cur: &mut Option<TimingPath>, paths: &mut Vec<TimingPath>| {
        if let Some(p) = cur.take() {
            let dup = paths
                .iter()
                .any(|q| q.source == p.source && q.dest == p.dest && q.slack_ns == p.slack_ns);
            if !p.steps.is_empty() && !dup {
                paths.push(p);
            }
        }
    };
    for line in text.lines() {
        if let Some(c) = TWR_SLACK.captures(line) {
            flush(&mut cur, &mut paths);
            in_steps = false;
            cur = Some(TimingPath {
                slack_ns: c[1].parse().unwrap_or(0.0),
                source: String::new(),
                dest: String::new(),
                delay_ns: None,
                levels: None,
                steps: Vec::new(),
            });
            continue;
        }
        let Some(p) = cur.as_mut() else { continue };
        if line.contains("Maximum Data Path:") {
            in_steps = true;
        } else if line.trim_start().starts_with("Total ") {
            in_steps = false;
        } else if in_steps {
            if let Some(c) = TWR_STEP.captures(line) {
                let kind = if c[3].starts_with("net") {
                    "net"
                } else {
                    &c[3]
                };
                p.steps.push(PathStep {
                    site: c[1].to_string(),
                    pin: c[2].to_string(),
                    kind: kind.to_string(),
                    delay_ns: c[4].parse().unwrap_or(0.0),
                    logical: c
                        .get(5)
                        .map(|m| vec![m.as_str().trim().to_string()])
                        .unwrap_or_default(),
                });
            } else if let (Some(c), Some(s)) = (TWR_MORE.captures(line), p.steps.last_mut()) {
                s.logical.push(c[1].trim().to_string());
            }
        } else if let Some(c) = TWR_ENDPOINT.captures(line) {
            if &c[1] == "Source" {
                p.source = c[2].to_string();
            } else {
                p.dest = c[2].to_string();
            }
        } else if let Some(c) = TWR_DELAY.captures(line) {
            p.delay_ns = c[1].parse().ok();
            p.levels = c[2].parse().ok();
        }
    }
    flush(&mut cur, &mut paths);
    paths.sort_by(|a, b| a.slack_ns.total_cmp(&b.slack_ns));
    paths
}

/// Top-level resource lines of a map report (`*_map.mrp`).
pub fn parse_map_report(text: &str) -> Vec<Resource> {
    text.lines()
        .filter_map(|l| MRP_ROW.captures(l))
        .map(|c| Resource {
            name: c[1].to_string(),
            used: n(&c[2]),
            available: n(&c[3]),
        })
        .collect()
}

#[derive(Debug, Clone, Default, PartialEq, Serialize)]
pub struct Timing {
    pub errors: Option<u64>,
    pub score: Option<u64>,
    pub min_period_ns: Option<f64>,
    pub fmax_mhz: Option<f64>,
}

impl Timing {
    pub fn met(&self) -> bool {
        self.errors == Some(0)
    }
}

static TWR_ERRORS: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"Timing errors:\s+(\d+)\s+Score:\s+(\d+)").unwrap());
static TWR_PERIOD: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"Minimum period:\s+([\d.]+)ns.*?Maximum frequency:\s+([\d.]+)MHz").unwrap()
});

/// Summary of a `trce` report (`*.twr`).
pub fn parse_timing_report(text: &str) -> Timing {
    let mut t = Timing::default();
    if let Some(c) = TWR_ERRORS.captures(text) {
        t.errors = c[1].parse().ok();
        t.score = c[2].parse().ok();
    }
    if let Some(c) = TWR_PERIOD.captures(text) {
        t.min_period_ns = c[1].parse().ok();
        t.fmax_mhz = c[2].parse().ok();
    }
    t
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct PadRow {
    pub pin: String,
    pub signal: String,
    pub direction: String,
    pub io_standard: String,
    /// `LOCATED` when the pin came from a constraint, `UNLOCATED` when ISE chose it.
    pub constraint: String,
}

/// User I/O rows of a pad report (`*_pad.txt`).
pub fn parse_pad_report(text: &str) -> Vec<PadRow> {
    text.lines()
        .filter(|l| l.starts_with('|'))
        .filter_map(|l| {
            let c: Vec<&str> = l.split('|').map(str::trim).collect();
            // ["", pin, signal, usage, pin name, direction, io std, bank, drive, slew,
            //  termination, iob delay, voltage, constraint, io register, signal integrity, ""]
            if c.len() < 15 || c[2].is_empty() || c[1] == "Pin Number" {
                return None;
            }
            Some(PadRow {
                pin: c[1].into(),
                signal: c[2].into(),
                direction: c[5].into(),
                io_standard: c[6].into(),
                constraint: c[13].into(),
            })
        })
        .collect()
}

/// Pins ISE placed by itself.
pub fn unlocated(rows: &[PadRow]) -> Vec<&PadRow> {
    rows.iter().filter(|r| r.constraint != "LOCATED").collect()
}

