//! Xilinx ISE 14.7 backend: ngdbuild → map → par → trce, then bitgen.
//!
//! Every tool runs through ISE's own `settings64.sh` so its environment
//! (XILINX, library paths) is exactly what Xilinx intended. Option spellings
//! were checked against the installed P.20131013 tools.

use std::path::{Path, PathBuf};
use std::sync::LazyLock;

use fpgaflow_core::job::JobSpec;
use fpgaflow_core::project::{ProgramMode, Project};
use fpgaflow_core::stage::Plan;
use fpgaflow_core::{tools, UserConfig};
use regex::Regex;
use serde::Serialize;

use crate::{constraint_files, part_name, PnrError};

/// Locate `settings64.sh` from the resolved `ngdbuild`
/// (`<ISE_DS>/ISE/bin/lin64/ngdbuild` → `<ISE_DS>/settings64.sh`).
pub fn settings_script(cfg: &UserConfig) -> Result<PathBuf, PnrError> {
    let ngdbuild = tools::resolve("ise-ngdbuild", cfg).ok_or(PnrError::NoIse)?;
    let ise_ds = ngdbuild.ancestors().nth(4).ok_or(PnrError::NoIse)?;
    let s = ise_ds.join("settings64.sh");
    if s.is_file() {
        Ok(s)
    } else {
        Err(PnrError::NoIse)
    }
}

/// `bash -c '<WRAP>' <settings> <tool> <args...>`
///
/// `settings64.sh` treats its first argument as the install location, so the
/// install directory (the script's own directory) is passed explicitly;
/// otherwise the tool's arguments would be taken for it.
const WRAP: &str = r#"source "$0" "${0%/*}" >/dev/null 2>&1; exec "$@""#;

fn job(settings: &Path, name: &str, workdir: &Path, tool: &str, args: &[&str]) -> JobSpec {
    JobSpec::new(name, "/bin/bash", workdir)
        .args(["-c", WRAP])
        .arg(settings)
        .arg(tool)
        .args(args.iter().copied())
}

/// Files an ISE run reads and writes, all in `build/impl`.
#[derive(Debug, Clone)]
pub struct IseFiles {
    pub workdir: PathBuf,
    pub top: String,
    pub ucf: PathBuf,
    pub ngd: PathBuf,
    pub map_ncd: PathBuf,
    pub ncd: PathBuf,
    pub pcf: PathBuf,
    pub mrp: PathBuf,
    pub twr: PathBuf,
    pub pad: PathBuf,
    pub bit: PathBuf,
}

impl IseFiles {
    pub fn new(workdir: PathBuf, top: &str) -> Self {
        let f = |s: &str| workdir.join(format!("{top}{s}"));
        Self {
            ucf: f(".ucf"),
            ngd: f(".ngd"),
            map_ncd: f("_map.ncd"),
            ncd: f(".ncd"),
            pcf: f(".pcf"),
            mrp: f("_map.mrp"),
            twr: f(".twr"),
            pad: f("_pad.txt"),
            bit: f(".bit"),
            top: top.to_string(),
            workdir,
        }
    }
}

#[derive(Debug, Clone)]
pub struct IsePlan {
    pub plan: Plan,
    pub files: IseFiles,
    pub settings: PathBuf,
    pub part: String,
    /// Where each source UCF starts in the combined UCF: (first line, source).
    pub ucf_sources: Vec<(u32, PathBuf)>,
}

impl IsePlan {
    /// Map a line of the combined UCF back to the source file and line.
    pub fn ucf_source_line(&self, line: u32) -> Option<(PathBuf, u32)> {
        self.ucf_sources
            .iter()
            .rev()
            .find(|(start, _)| *start <= line)
            .map(|(start, src)| (src.clone(), line - start + 1))
    }

    /// Point diagnostics on the combined UCF at the user's own files.
    pub fn remap(&self, diags: &mut [fpgaflow_core::diag::Diagnostic]) {
        for d in diags {
            let is_combined =
                d.file == self.files.ucf || d.file.file_name() == self.files.ucf.file_name();
            if is_combined {
                if let Some((src, line)) = self.ucf_source_line(d.line) {
                    d.file = src;
                    d.line = line;
                }
            }
        }
    }
}

/// Plan translate, map, place & route and static timing.
///
/// The project's constraint files are concatenated into one UCF (ngdbuild
/// takes a single `-uc`). The stale bitstream is deleted up front so a failed
/// run can never leave an old `.bit` looking current.
pub fn plan_implement(
    project: &Project,
    cfg: &UserConfig,
    netlist: &Path,
    top: &str,
) -> Result<IsePlan, PnrError> {
    let settings = settings_script(cfg)?;
    let target = project
        .file
        .target
        .as_ref()
        .ok_or(PnrError::MissingTarget("device"))?;
    let part = part_name(target)?;
    let sources = constraint_files(project);
    if sources.is_empty() {
        return Err(PnrError::NoConstraints);
    }
    let mut ucf =
        String::from("# Generated by fpgaflow from the project's [target] constraints.\n");
    let mut ucf_sources = Vec::new();
    for src in &sources {
        let text = std::fs::read_to_string(src).map_err(|source| PnrError::Io {
            path: src.clone(),
            source,
        })?;
        ucf.push_str(&format!(
            "\n# ---- {}\n",
            src.strip_prefix(&project.root).unwrap_or(src).display()
        ));
        ucf_sources.push((ucf.lines().count() as u32 + 1, src.clone()));
        ucf.push_str(&text);
        if !text.ends_with('\n') {
            ucf.push('\n');
        }
    }
    // Pins the board reserves: ISE must never place anything there either.
    if let Some(b) = crate::project_board(project) {
        if b.reserved_pins().next().is_some() {
            ucf.push_str(&format!(
                "\n# ---- {}: reserved pins (data/boards.toml)\n",
                b.name
            ));
            for pin in b.reserved_pins() {
                ucf.push_str(&format!(
                    "CONFIG PROHIBIT = \"{pin}\"; # {}\n",
                    b.reserved_reason(pin).unwrap_or("")
                ));
            }
        }
    }

    let files = IseFiles::new(project.stage_dir("impl"), top);
    let w = &files.workdir;
    let s = |p: &Path| p.file_name().unwrap().to_string_lossy().into_owned();
    let netlist_s = netlist.to_string_lossy().into_owned();
    let jobs = vec![
        job(
            &settings,
            "ise:ngdbuild",
            w,
            "ngdbuild",
            &[
                "-p",
                &part,
                "-uc",
                &s(&files.ucf),
                "-dd",
                "_ngo",
                &netlist_s,
                &s(&files.ngd),
            ],
        ),
        job(
            &settings,
            "ise:map",
            w,
            "map",
            &[
                "-w",
                "-o",
                &s(&files.map_ncd),
                &s(&files.ngd),
                &s(&files.pcf),
            ],
        ),
        job(
            &settings,
            "ise:par",
            w,
            "par",
            &["-w", &s(&files.map_ncd), &s(&files.ncd), &s(&files.pcf)],
        ),
        job(
            &settings,
            "ise:trce",
            w,
            "trce",
            &[
                "-v",
                "3",
                "-u",
                "3",
                "-o",
                &s(&files.twr),
                &s(&files.ncd),
                &s(&files.pcf),
            ],
        ),
    ];
    let plan = Plan {
        stage: "impl".into(),
        workdir: w.clone(),
        jobs,
        outputs: vec![
            files.ngd.clone(),
            files.map_ncd.clone(),
            files.ncd.clone(),
            files.pcf.clone(),
            files.mrp.clone(),
            files.twr.clone(),
            files.pad.clone(),
            files.bit.clone(),
        ],
        verdict_job: None,
        files: vec![(files.ucf.clone(), ucf)],
    };
    Ok(IsePlan {
        plan,
        files,
        settings,
        part,
        ucf_sources,
    })
}

/// Plan bitgen. The start-up clock follows how the bitstream will be loaded:
/// JTAG for a volatile SRAM load, CCLK when it boots from flash. `extra` are
/// the board's own `-g` options (`Name:Value`); a `StartupClk` among them
/// wins, for boards loaded over SelectMAP like the Celoxica RC10.
pub fn plan_bitstream(ip: &IsePlan, mode: ProgramMode, extra: &[String]) -> Plan {
    let f = &ip.files;
    let s = |p: &Path| p.file_name().unwrap().to_string_lossy().into_owned();
    let clk = match mode {
        ProgramMode::Sram => "StartupClk:JtagClk",
        ProgramMode::Flash => "StartupClk:Cclk",
    };
    let mut args: Vec<String> = vec!["-w".into()];
    if !extra.iter().any(|g| g.starts_with("StartupClk:")) {
        args.extend(["-g".into(), clk.into()]);
    }
    for g in extra {
        args.extend(["-g".into(), g.clone()]);
    }
    args.extend([s(&f.ncd), s(&f.bit), s(&f.pcf)]);
    let args: Vec<&str> = args.iter().map(String::as_str).collect();
    Plan {
        stage: "bitstream".into(),
        workdir: f.workdir.clone(),
        jobs: vec![job(&ip.settings, "ise:bitgen", &f.workdir, "bitgen", &args)],
        outputs: vec![f.bit.clone()],
        verdict_job: None,
        files: vec![],
    }
}

