//! Tables for the RTL, generated from the same source as the model
//! (`mp3model rtl-tables DIR`).

use std::fmt::Write;

use crate::fixed::{coef_tables, pow43_entry};
use crate::frontend::HW;
use crate::tables::{Code, COUNT1, LINBITS, PAIRS, PRETAB, SFB_LONG, SFB_SHORT, SLEN};

/// The Huffman codes as one array of tree nodes. Node word = {child for 0,
/// child for 1}, 12 bits each: bit 11 set = leaf with the value in bits 7..0
/// (x << 4 | y, or v w x y for count1); clear = index of the next node.
/// Returns (nodes, root node of tables 0..31 then count1 A and B; None for
/// the empty tables 0, 4 and 14).
pub fn huffman_nodes() -> (Vec<[u16; 2]>, [Option<u16>; 34]) {
    let mut nodes: Vec<[u16; 2]> = Vec::new();
    let mut roots = [None; 34];
    let mut seen: Vec<(*const Code, u16)> = Vec::new();
    let codes: Vec<&[Code]> = PAIRS
        .iter()
        .copied()
        .chain([&COUNT1[0][..], &COUNT1[1][..]])
        .collect();
    for (t, list) in codes.iter().enumerate() {
        if list.is_empty() {
            continue;
        }
        if let Some(&(_, r)) = seen.iter().find(|(p, _)| *p == list.as_ptr()) {
            roots[t] = Some(r);
            continue;
        }
        let root = nodes.len();
        nodes.push([0, 0]);
        for c in list.iter() {
            let mut n = root;
            for i in (0..c.len).rev() {
                let bit = ((c.code as u32 >> i) & 1) as usize;
                if i == 0 {
                    nodes[n][bit] = 0x800 | ((c.x as u16) << 4 | c.y as u16);
                } else {
                    if nodes[n][bit] == 0 {
                        nodes.push([0, 0]);
                        nodes[n][bit] = (nodes.len() - 1) as u16;
                    }
                    n = nodes[n][bit] as usize;
                }
            }
        }
        roots[t] = Some(root as u16);
        seen.push((list.as_ptr(), root as u16));
    }
    (nodes, roots)
}

/// SystemVerilog for the Huffman tree ROM (block RAM, registered read) and
/// its table roots.
pub fn huffman_sv() -> String {
    let (nodes, roots) = huffman_nodes();
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// Generated by `mp3model rtl-tables` from crates/mp3model/src/tables.rs; do not edit."
    );
    let _ = writeln!(s, "`timescale 1ns/1ps\n");
    let _ = writeln!(
        s,
        "// Huffman decode trees: {} nodes. Word = {{child for 0, child for 1}};",
        nodes.len()
    );
    let _ = writeln!(
        s,
        "// a child with bit 11 set is a leaf (value in bits 7..0), else a node index."
    );
    let _ = writeln!(s, "module huff_rom (\n    input  logic        clk,\n    input  logic [10:0] addr,\n    output logic [23:0] data\n);");
    let _ = writeln!(s, "    logic [23:0] rom [0:{}];", nodes.len() - 1);
    let _ = writeln!(s, "    initial begin");
    for (i, n) in nodes.iter().enumerate() {
        let _ = writeln!(s, "        rom[{i}] = 24'h{:03x}{:03x};", n[0], n[1]);
    }
    let _ = writeln!(s, "    end");
    let _ = writeln!(
        s,
        "    always_ff @(posedge clk) data <= rom[addr];\nendmodule\n"
    );
    let _ = writeln!(
        s,
        "// Root node of tables 0..31, count1 A (32) and B (33); `empty` for 0, 4, 14."
    );
    let _ = writeln!(s, "module huff_root (\n    input  logic [5:0]  table_no,\n    output logic [10:0] root,\n    output logic        empty\n);");
    let _ = writeln!(
        s,
        "    always_comb begin\n        empty = 1'b0;\n        case (table_no)"
    );
    for (t, r) in roots.iter().enumerate() {
        match r {
            Some(r) => {
                let _ = writeln!(s, "            6'd{t}: root = 11'd{r};");
            }
            None => {
                let _ = writeln!(
                    s,
                    "            6'd{t}: begin root = 11'd0; empty = 1'b1; end"
                );
            }
        }
    }
    let _ = writeln!(s, "            default: begin root = 11'd0; empty = 1'b1; end\n        endcase\n    end\nendmodule");
    s
}

/// SystemVerilog lookup modules for the small tables: long-block band edges,
/// linbits and the scale factor lengths.
pub fn tables_sv() -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// Generated by `mp3model rtl-tables` from crates/mp3model/src/tables.rs; do not edit."
    );
    let _ = writeln!(s, "`timescale 1ns/1ps\n");
    let _ = writeln!(
        s,
        "// Long-block scale factor band edge `idx` (0..22) for rate 0 = 44.1, 1 = 48, 2 = 32 kHz."
    );
    let _ = writeln!(s, "module mp3_sfb_long (\n    input  logic [1:0]  rate,\n    input  logic [4:0]  idx,\n    output logic [9:0]  edge_\n);");
    let _ = writeln!(s, "    always_comb\n        case ({{rate, idx}})");
    for (r, edges) in SFB_LONG.iter().enumerate() {
        for (i, e) in edges.iter().enumerate() {
            let _ = writeln!(s, "            {{2'd{r}, 5'd{i}}}: edge_ = 10'd{e};");
        }
    }
    let _ = writeln!(
        s,
        "            default: edge_ = 10'd576;\n        endcase\nendmodule\n"
    );
    let _ = writeln!(s, "module mp3_linbits (\n    input  logic [4:0] table_no,\n    output logic [3:0] linbits\n);");
    let _ = writeln!(s, "    always_comb\n        case (table_no)");
    for (t, l) in LINBITS.iter().enumerate() {
        let _ = writeln!(s, "            5'd{t}: linbits = 4'd{l};");
    }
    let _ = writeln!(
        s,
        "            default: linbits = 4'd0;\n        endcase\nendmodule\n"
    );
    let _ = writeln!(s, "module mp3_slen (\n    input  logic [3:0] sfc,\n    output logic [2:0] slen1,\n    output logic [2:0] slen2\n);");
    let _ = writeln!(s, "    always_comb\n        case (sfc)");
    for (c, (a, b)) in SLEN.iter().enumerate() {
        let _ = writeln!(
            s,
            "            4'd{c}: begin slen1 = 3'd{a}; slen2 = 3'd{b}; end"
        );
    }
    let _ = writeln!(
        s,
        "            default: begin slen1 = 3'd0; slen2 = 3'd0; end\n        endcase\nendmodule"
    );
    s
}

/// SystemVerilog for milestone 3: the |n|^(4/3) table (dual-port block RAM),
/// short-block band edges, pretab, the short-block reorder map, and the
/// stereo / antialias coefficients.
pub fn spectral_sv() -> String {
    let mut s = String::new();
    let m = HW.m;
    let _ = writeln!(
        s,
        "// Generated by `mp3model rtl-tables` from crates/mp3model; do not edit."
    );
    let _ = writeln!(s, "`timescale 1ns/1ps\n");
    let _ = writeln!(s, "// n^(4/3) for n = 0..1026: {{exponent[3:0], mantissa[{}:0]}}, n^(4/3) ~ mantissa * 2^(exponent - {}).", m - 1, m - 1);
    let _ = writeln!(
        s,
        "// Two registered read ports (interpolation needs entries k and k+1). Mantissas"
    );
    let _ = writeln!(
        s,
        "// and exponents are separate ROMs, no port wider than 18 bits: on Spartan-3 a"
    );
    let _ = writeln!(
        s,
        "// wide block RAM port competes for routing with the multiplier beside it."
    );
    let _ = writeln!(s, "// Entries 1024..1026 are a small lookup.");
    let _ = writeln!(s, "module mp3_pow43 (\n    input  logic        clk,\n    input  logic [10:0] addr_a,\n    input  logic [10:0] addr_b,");
    let _ = writeln!(
        s,
        "    output logic [{w}:0] data_a,\n    output logic [{w}:0] data_b\n);",
        w = m + 3
    );
    let _ = writeln!(
        s,
        "    logic [{}:0] mrom [0:1023];\n    logic [3:0]  erom [0:1023];\n    initial begin",
        m - 1
    );
    for n in 0..1024u32 {
        let (mant, e) = pow43_entry(n, m);
        let _ = writeln!(
            s,
            "        mrom[{n}] = {m}'h{mant:x}; erom[{n}] = 4'h{e:x};"
        );
    }
    let _ = writeln!(s, "    end");
    let _ = writeln!(
        s,
        "    function automatic logic [{}:0] top(input logic [1:0] i);\n        case (i)",
        m + 3
    );
    for n in 1024..=1026u32 {
        let (mant, e) = pow43_entry(n, m);
        let _ = writeln!(
            s,
            "            2'd{}: top = {}'h{:x};",
            n - 1024,
            m + 4,
            ((e as u64) << m) | mant as u64
        );
    }
    let _ = writeln!(
        s,
        "            default: top = '0;\n        endcase\n    endfunction"
    );
    let _ = writeln!(s, "    logic [{}:0] ma, mb;\n    logic [3:0] ea, eb;\n    logic hi_a, hi_b;\n    logic [1:0] ia, ib;", m - 1);
    let _ = writeln!(s, "    always_ff @(posedge clk) begin\n        ma <= mrom[addr_a[9:0]]; ea <= erom[addr_a[9:0]];");
    let _ = writeln!(
        s,
        "        mb <= mrom[addr_b[9:0]]; eb <= erom[addr_b[9:0]];"
    );
    let _ = writeln!(s, "        hi_a <= addr_a[10]; ia <= addr_a[1:0];\n        hi_b <= addr_b[10]; ib <= addr_b[1:0];\n    end");
    let _ = writeln!(s, "    assign data_a = hi_a ? top(ia) : {{ea, ma}};\n    assign data_b = hi_b ? top(ib) : {{eb, mb}};\nendmodule\n");

    let _ = writeln!(
        s,
        "// Short-block band edge `idx` (0..13) for rate 0 = 44.1, 1 = 48, 2 = 32 kHz."
    );
    let _ = writeln!(s, "module mp3_sfb_short (\n    input  logic [1:0] rate,\n    input  logic [3:0] idx,\n    output logic [7:0] edge_\n);");
    let _ = writeln!(s, "    always_comb\n        case ({{rate, idx}})");
    for (r, edges) in SFB_SHORT.iter().enumerate() {
        for (i, e) in edges.iter().enumerate() {
            let _ = writeln!(s, "            {{2'd{r}, 4'd{i}}}: edge_ = 8'd{e};");
        }
    }
    let _ = writeln!(
        s,
        "            default: edge_ = 8'd192;\n        endcase\nendmodule\n"
    );

    let _ = writeln!(
        s,
        "module mp3_pretab (\n    input  logic [4:0] band,\n    output logic [1:0] pre\n);"
    );
    let _ = writeln!(s, "    always_comb\n        case (band)");
    for (b, p) in PRETAB.iter().enumerate() {
        let _ = writeln!(s, "            5'd{b}: pre = 2'd{p};");
    }
    let _ = writeln!(
        s,
        "            default: pre = 2'd0;\n        endcase\nendmodule\n"
    );

    let _ = writeln!(
        s,
        "// Short blocks: the coded-order index of hybrid index k (band, frequency,"
    );
    let _ = writeln!(s, "// window order), per rate; registered read.");
    let _ = writeln!(s, "module mp3_reorder (\n    input  logic       clk,\n    input  logic [1:0] rate,\n    input  logic [9:0] k,\n    output logic [9:0] coded\n);");
    let _ = writeln!(s, "    logic [9:0] rom [0:2047];\n    initial begin");
    for (r, edges) in SFB_SHORT.iter().enumerate() {
        let mut map = vec![0u16; 576];
        for band in 0..13 {
            let (lo, hi) = (edges[band] as usize, edges[band + 1] as usize);
            let width = hi - lo;
            for w in 0..3 {
                for k in 0..width {
                    map[3 * lo + 3 * k + w] = (3 * lo + w * width + k) as u16;
                }
            }
        }
        for (k, c) in map.iter().enumerate() {
            let _ = writeln!(s, "        rom[{}] = 10'd{c};", r * 576 + k);
        }
    }
    let _ = writeln!(s, "    end\n    always_ff @(posedge clk) coded <= rom[11'(rate) * 11'd576 + 11'(k)];\nendmodule\n");

    let _ = writeln!(
        s,
        "// 2^(k/4), k = 0..3, as {}-bit unsigned with {} fraction bits.",
        m,
        m - 1
    );
    let _ = writeln!(
        s,
        "module mp3_frac4 (\n    input  logic [1:0]  k,\n    output logic [{}:0] v\n);",
        m - 1
    );
    let _ = writeln!(s, "    always_comb\n        case (k)");
    for k in 0..4 {
        let v = (2f64.powf(k as f64 / 4.0) * (1u64 << (m - 1)) as f64).round() as u64;
        let _ = writeln!(s, "            2'd{k}: v = {m}'d{v};");
    }
    let _ = writeln!(s, "        endcase\nendmodule\n");

    let (cs, ca, ms, isk) = coef_tables(&HW);
    let _ = writeln!(
        s,
        "// Coefficients, 18-bit signed with 17 fraction bits (as crates/mp3model/src/fixed.rs)."
    );
    let _ = writeln!(
        s,
        "module mp3_coefs (\n    input  logic [2:0]  aa_i,\n    input  logic [2:0]  is_pos,"
    );
    let _ = writeln!(s, "    output logic signed [17:0] aa_cs,\n    output logic signed [17:0] aa_ca,\n    output logic signed [17:0] ms,");
    let _ = writeln!(
        s,
        "    output logic signed [17:0] is_kl,\n    output logic signed [17:0] is_kr\n);"
    );
    let _ = writeln!(
        s,
        "    assign ms = 18'sd{ms};\n    always_comb begin\n        case (aa_i)"
    );
    for i in 0..8 {
        let _ = writeln!(
            s,
            "            3'd{i}: begin aa_cs = 18'sd{}; aa_ca = -18'sd{}; end",
            cs[i], -ca[i]
        );
    }
    let _ = writeln!(s, "            default: begin aa_cs = '0; aa_ca = '0; end\n        endcase\n        case (is_pos)");
    for (p, (kl, kr)) in isk.iter().enumerate() {
        // A gain of exactly 1.0 (k_left at position 6, k_right at 0) doesn't
        // fit: the RTL passes the value through there.
        let (kl, kr) = ((*kl).min((1 << 17) - 1), (*kr).min((1 << 17) - 1));
        let _ = writeln!(
            s,
            "            3'd{p}: begin is_kl = 18'sd{kl}; is_kr = 18'sd{kr}; end"
        );
    }
    let _ = writeln!(s, "            default: begin is_kl = '0; is_kr = '0; end\n        endcase\n    end\nendmodule");
    s
}

#[cfg(test)]
mod tests {
    #[test]
    fn nodes_fit_and_every_table_has_a_root() {
        let (nodes, roots) = super::huffman_nodes();
        assert!(
            nodes.len() < 2048,
            "{} nodes need more than 11 bits",
            nodes.len()
        );
        for (t, r) in roots.iter().enumerate() {
            assert_eq!(r.is_none(), [0, 4, 14].contains(&t), "table {t}");
        }
    }
}
