//! Tables for the RTL, generated from the same source as the model
//! (`mp3model rtl-tables DIR`).

use std::fmt::Write;

use crate::tables::{Code, COUNT1, LINBITS, PAIRS, SFB_LONG, SLEN};

/// The Huffman codes as one array of tree nodes. Node word = {child for 0,
/// child for 1}, 12 bits each: bit 11 set = leaf with the value in bits 7..0
/// (x << 4 | y, or v w x y for count1); clear = index of the next node.
/// Returns (nodes, root node of tables 0..31 then count1 A and B; None for
/// the empty tables 0, 4 and 14).
pub fn huffman_nodes() -> (Vec<[u16; 2]>, [Option<u16>; 34]) {
    let mut nodes: Vec<[u16; 2]> = Vec::new();
    let mut roots = [None; 34];
    let mut seen: Vec<(*const Code, u16)> = Vec::new();
    let codes: Vec<&[Code]> = PAIRS
        .iter()
        .copied()
        .chain([&COUNT1[0][..], &COUNT1[1][..]])
        .collect();
    for (t, list) in codes.iter().enumerate() {
        if list.is_empty() {
            continue;
        }
        if let Some(&(_, r)) = seen.iter().find(|(p, _)| *p == list.as_ptr()) {
            roots[t] = Some(r);
            continue;
        }
        let root = nodes.len();
        nodes.push([0, 0]);
        for c in list.iter() {
            let mut n = root;
            for i in (0..c.len).rev() {
                let bit = ((c.code as u32 >> i) & 1) as usize;
                if i == 0 {
                    nodes[n][bit] = 0x800 | ((c.x as u16) << 4 | c.y as u16);
                } else {
                    if nodes[n][bit] == 0 {
                        nodes.push([0, 0]);
                        nodes[n][bit] = (nodes.len() - 1) as u16;
                    }
                    n = nodes[n][bit] as usize;
                }
            }
        }
        roots[t] = Some(root as u16);
        seen.push((list.as_ptr(), root as u16));
    }
    (nodes, roots)
}

/// SystemVerilog for the Huffman tree ROM (block RAM, registered read) and
/// its table roots.
pub fn huffman_sv() -> String {
    let (nodes, roots) = huffman_nodes();
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// Generated by `mp3model rtl-tables` from crates/mp3model/src/tables.rs; do not edit."
    );
    let _ = writeln!(s, "`timescale 1ns/1ps\n");
    let _ = writeln!(
        s,
        "// Huffman decode trees: {} nodes. Word = {{child for 0, child for 1}};",
        nodes.len()
    );
    let _ = writeln!(
        s,
        "// a child with bit 11 set is a leaf (value in bits 7..0), else a node index."
    );
    let _ = writeln!(s, "module huff_rom (\n    input  logic        clk,\n    input  logic [10:0] addr,\n    output logic [23:0] data\n);");
    let _ = writeln!(s, "    logic [23:0] rom [0:{}];", nodes.len() - 1);
    let _ = writeln!(s, "    initial begin");
    for (i, n) in nodes.iter().enumerate() {
        let _ = writeln!(s, "        rom[{i}] = 24'h{:03x}{:03x};", n[0], n[1]);
    }
    let _ = writeln!(s, "    end");
    let _ = writeln!(
        s,
        "    always_ff @(posedge clk) data <= rom[addr];\nendmodule\n"
    );
    let _ = writeln!(
        s,
        "// Root node of tables 0..31, count1 A (32) and B (33); `empty` for 0, 4, 14."
    );
    let _ = writeln!(s, "module huff_root (\n    input  logic [5:0]  table_no,\n    output logic [10:0] root,\n    output logic        empty\n);");
    let _ = writeln!(
        s,
        "    always_comb begin\n        empty = 1'b0;\n        case (table_no)"
    );
    for (t, r) in roots.iter().enumerate() {
        match r {
            Some(r) => {
                let _ = writeln!(s, "            6'd{t}: root = 11'd{r};");
            }
            None => {
                let _ = writeln!(
                    s,
                    "            6'd{t}: begin root = 11'd0; empty = 1'b1; end"
                );
            }
        }
    }
    let _ = writeln!(s, "            default: begin root = 11'd0; empty = 1'b1; end\n        endcase\n    end\nendmodule");
    s
}

/// SystemVerilog lookup modules for the small tables: long-block band edges,
/// linbits and the scale factor lengths.
pub fn tables_sv() -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// Generated by `mp3model rtl-tables` from crates/mp3model/src/tables.rs; do not edit."
    );
    let _ = writeln!(s, "`timescale 1ns/1ps\n");
    let _ = writeln!(
        s,
        "// Long-block scale factor band edge `idx` (0..22) for rate 0 = 44.1, 1 = 48, 2 = 32 kHz."
    );
    let _ = writeln!(s, "module mp3_sfb_long (\n    input  logic [1:0]  rate,\n    input  logic [4:0]  idx,\n    output logic [9:0]  edge_\n);");
    let _ = writeln!(s, "    always_comb\n        case ({{rate, idx}})");
    for (r, edges) in SFB_LONG.iter().enumerate() {
        for (i, e) in edges.iter().enumerate() {
            let _ = writeln!(s, "            {{2'd{r}, 5'd{i}}}: edge_ = 10'd{e};");
        }
    }
    let _ = writeln!(
        s,
        "            default: edge_ = 10'd576;\n        endcase\nendmodule\n"
    );
    let _ = writeln!(s, "module mp3_linbits (\n    input  logic [4:0] table_no,\n    output logic [3:0] linbits\n);");
    let _ = writeln!(s, "    always_comb\n        case (table_no)");
    for (t, l) in LINBITS.iter().enumerate() {
        let _ = writeln!(s, "            5'd{t}: linbits = 4'd{l};");
    }
    let _ = writeln!(
        s,
        "            default: linbits = 4'd0;\n        endcase\nendmodule\n"
    );
    let _ = writeln!(s, "module mp3_slen (\n    input  logic [3:0] sfc,\n    output logic [2:0] slen1,\n    output logic [2:0] slen2\n);");
    let _ = writeln!(s, "    always_comb\n        case (sfc)");
    for (c, (a, b)) in SLEN.iter().enumerate() {
        let _ = writeln!(
            s,
            "            4'd{c}: begin slen1 = 3'd{a}; slen2 = 3'd{b}; end"
        );
    }
    let _ = writeln!(
        s,
        "            default: begin slen1 = 3'd0; slen2 = 3'd0; end\n        endcase\nendmodule"
    );
    s
}

#[cfg(test)]
mod tests {
    #[test]
    fn nodes_fit_and_every_table_has_a_root() {
        let (nodes, roots) = super::huffman_nodes();
        assert!(
            nodes.len() < 2048,
            "{} nodes need more than 11 bits",
            nodes.len()
        );
        for (t, r) in roots.iter().enumerate() {
            assert_eq!(r.is_none(), [0, 4, 14].contains(&t), "table {t}");
        }
    }
}
