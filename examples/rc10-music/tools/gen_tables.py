#!/usr/bin/env python3
"""Generate rtl/note_table.sv and rtl/tunes.sv for the RC10 music demo.

Notes are 6-bit numbers n = MIDI - 36 (C2 = 0 ... D7 = 62); 63 is a rest.
Each tune entry is 16 bits: {last, melody[5:0], len-1[2:0], bass[5:0]},
len in eighth notes (1..8). The tunes are public-domain melodies.

    python3 tools/gen_tables.py   # from examples/rc10-music/
"""
from pathlib import Path

CLK_HZ = 48_000_000
REST = 63
NAMES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def note(s):
    """'E5' -> n, 'R' -> rest."""
    if s == "R":
        return REST
    pc = NAMES[s[0]] + (1 if "#" in s else 0)
    octave = int(s[-1])
    n = (octave + 1) * 12 + pc - 36
    assert 0 <= n < REST, s
    return n


def inc(n):
    """32-bit DDS phase increment at CLK_HZ for note n."""
    f = 440.0 * 2 ** ((n + 36 - 69) / 12)
    return round(f * 2**32 / CLK_HZ)


# (melody, eighths, bass)
ODE = (
    [("E5", 2, "C3"), ("E5", 2, "C3"), ("F5", 2, "C3"), ("G5", 2, "C3"),
     ("G5", 2, "G2"), ("F5", 2, "G2"), ("E5", 2, "C3"), ("D5", 2, "G2"),
     ("C5", 2, "C3"), ("C5", 2, "C3"), ("D5", 2, "G2"), ("E5", 2, "C3"),
     ("E5", 3, "C3"), ("D5", 1, "G2"), ("D5", 4, "G2"),
     ("E5", 2, "C3"), ("E5", 2, "C3"), ("F5", 2, "C3"), ("G5", 2, "C3"),
     ("G5", 2, "G2"), ("F5", 2, "G2"), ("E5", 2, "C3"), ("D5", 2, "G2"),
     ("C5", 2, "C3"), ("C5", 2, "C3"), ("D5", 2, "G2"), ("E5", 2, "C3"),
     ("D5", 3, "G2"), ("C5", 1, "C3"), ("C5", 4, "C3"),
     ("R", 4, "R")]
)
_tw_a = [("C5", 2, "C3"), ("C5", 2, "C3"), ("G5", 2, "C3"), ("G5", 2, "C3"),
         ("A5", 2, "F2"), ("A5", 2, "F2"), ("G5", 4, "C3")]
_tw_b = [("F5", 2, "F2"), ("F5", 2, "F2"), ("E5", 2, "C3"), ("E5", 2, "C3"),
         ("D5", 2, "G2"), ("D5", 2, "G2"), ("C5", 4, "C3")]
_tw_c = [("G5", 2, "C3"), ("G5", 2, "C3"), ("F5", 2, "F2"), ("F5", 2, "F2"),
         ("E5", 2, "C3"), ("E5", 2, "C3"), ("D5", 4, "G2")]
TWINKLE = _tw_a + _tw_b + _tw_c + _tw_c + _tw_a + _tw_b + [("R", 4, "R")]
_fj_1 = [("C5", 2, "C3"), ("D5", 2, "C3"), ("E5", 2, "C3"), ("C5", 2, "C3")]
_fj_2 = [("E5", 2, "C3"), ("F5", 2, "C3"), ("G5", 4, "C3")]
_fj_3 = [("G5", 1, "C3"), ("A5", 1, "C3"), ("G5", 1, "C3"), ("F5", 1, "C3"),
         ("E5", 2, "C3"), ("C5", 2, "C3")]
_fj_4 = [("C5", 2, "C3"), ("G4", 2, "G2"), ("C5", 4, "C3")]
FRERE = _fj_1 * 2 + _fj_2 * 2 + _fj_3 * 2 + _fj_4 * 2 + [("R", 4, "R")]

TUNES = [("Ode to Joy", ODE), ("Twinkle Twinkle Little Star", TWINKLE),
         ("Frere Jacques", FRERE)]


def entry(m, length, b, last):
    assert 1 <= length <= 8
    return (int(last) << 15) | (note(m) << 9) | ((length - 1) << 6) | note(b)


def main():
    here = Path(__file__).resolve().parent.parent / "rtl"
    hdr = "`timescale 1ns/1ps\n\n// Generated by tools/gen_tables.py; do not edit.\n"

    lines = [hdr,
             "// 32-bit DDS phase increment for note n = MIDI - 36 at 48 MHz; 63 = rest.",
             "module note_table (",
             "    input  logic [5:0]  n,",
             "    output logic [31:0] inc",
             ");",
             "    always_comb begin",
             "        case (n)"]
    for n in range(REST):
        lines.append(f"            6'd{n}: inc = 32'd{inc(n)};")
    lines += ["            default: inc = 32'd0;", "        endcase", "    end",
              "endmodule", ""]
    (here / "note_table.sv").write_text("\n".join(lines))

    lines = [hdr,
             "// Tune ROM: addr = {tune[1:0], index[5:0]}; data =",
             "// {last, melody[5:0], len-1[2:0], bass[5:0]}, len in eighth notes.",
             "module tunes (",
             "    input  logic [7:0]  addr,",
             "    output logic [15:0] data",
             ");",
             "    always_comb begin",
             "        case (addr)"]
    for t, (name, notes) in enumerate(TUNES):
        assert len(notes) <= 64, name
        lines.append(f"            // tune {t}: {name} ({len(notes)} entries)")
        for i, (m, length, b) in enumerate(notes):
            e = entry(m, length, b, i == len(notes) - 1)
            lines.append(f"            8'd{t * 64 + i}: data = 16'h{e:04x};  // {m} x{length}, bass {b}")
    lines += [f"            default: data = 16'h{entry('R', 4, 'R', True):04x};  // rest, end",
              "        endcase", "    end", "endmodule", ""]
    (here / "tunes.sv").write_text("\n".join(lines))
    for name, notes in TUNES:
        print(f"{name}: {len(notes)} entries, {sum(n[1] for n in notes)} eighths")


if __name__ == "__main__":
    main()
